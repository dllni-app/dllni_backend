  <h1>إشعار استخدام الموقع — تجربة مراقبة التزام مقدّمي خدمات التنظيف</h1>
  <p class="note"><strong>المشاركة اختيارية.</strong> لا يبدأ جمع المواقع الخاص بهذه التجربة حتى توافق داخل التطبيق وتمنح إذن نظام التشغيل. يمكنك الرفض والاستمرار باستخدام التطبيق، أو إيقاف المشاركة لاحقاً.</p>
  <h2>البيانات التي تُجمع</h2>
  <p>إذا وافقت على التجربة وكان حسابك مدرجاً فيها، قد يطلب تطبيق «ع الندهة» موقع الجهاز الدقيق كل دقيقتين تقريباً، في الواجهة أو الخلفية أو خارج أوقات الطلبات، ما دام نظام التشغيل يسمح بذلك. نحتفظ بوقت القياس ودقته وحالة صلاحيات الموقع، ولا نضمن استمرار جمع البيانات عند إيقاف التطبيق قسرياً أو انقطاع الاتصال أو تعطيل خدمات الموقع.</p>
  <h2>الغرض من المعالجة</h2>
  <p>مراجعة مؤشرات الالتزام بسياسات المنصة ومقارنتها بمواقع طلبات تنظيف أُنجزت سابقاً. مجرد القرب من موقع لا يعني مخالفة ولا يولّد عقوبة آلية. يجب أن تتم مراجعة أي حالة بواسطة أشخاص مخوّلين وبالاستناد إلى أدلة مستقلة وإتاحة فرصة للعامل للرد.</p>
  <h2>من يمكنه الاطلاع؟</h2>
  <p>موظفو المراجعة المصرّح لهم فقط، مع سجل للعمليات. تعرض شاشة المراجعة مؤشرات عامة وأرقاماً مرجعية، ولا تعرض العنوان الدقيق للزبون أو مسار الموقع الكامل ضمن الإشعار الإداري.</p>
  <h2>الاحتفاظ والأمان</h2>
  <ul>
    <li>عينات الموقع الأولية: حتى 7 أيام، مع التشفير عند التخزين.</li>
    <li>بصمات مواقع الزيارات المؤهلة: حتى 90 يوماً.</li>
    <li>حالات المراجعة: حتى 90 يوماً، وسجل إجراءات المراجعة حتى 180 يوماً.</li>
  </ul>
  <h2>الرفض أو سحب الموافقة</h2>
  <p>اختر «المتابعة دون مراقبة الموقع خارج المهام» عندما يظهر الإشعار، أو أوقف المشاركة الاختيارية من التطبيق. عند الإيقاف تُلغى جلسة المراقبة؛ ويستمر أي استخدام للموقع مطلوب لتنفيذ طلب قبلته أو لخدمات الطوارئ وفق الصلاحيات الممنوحة لذلك الغرض. ويمكن التواصل مع الدعم داخل التطبيق للاستفسار أو طلب مراجعة وتصحيح البيانات حسب ما يسمح به القانون.</p>
  <h2>إشعارات الإدارة</h2>
  <p>عند تفعيل إشعارات المراجعة، تُرسل إشارة عامة لموظفي الإدارة المخوّلين بوجود حالة تتطلب التحقق، من دون إدراج إحداثيات أو معلومات الزبون في متن الإشعار.</p>
